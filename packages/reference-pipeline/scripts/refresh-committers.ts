/**
 * Spec 019 amendment (7), owner resolution 3 (W103): `bun run refresh:committers -- --reviewer <login>`
 * reads the Kafka committers page once (anonymous, read-only), rewrites the committed capture
 * beside the Kafka profile, and prints the pairs added, removed and changed for the owner to review
 * in a PR. No cron reads the page.
 *
 *   --reviewer <login>  who reviews the refresh PR (written into added and changed pairs)
 *   --date <YYYY-MM-DD> the capture date (default: today, UTC)
 *   --html <file>       read a saved page instead of the network (tests, offline review)
 *   --capture <file>    the capture module to rewrite (default: the Kafka capture)
 *   --check             print the diff without writing
 */
import { join } from "node:path";

import {
  formatCommittersDiff,
  KAFKA_COMMITTERS_URL,
  parseCommittersPage,
  refreshCommitters,
  type CommittersCaptureV1,
} from "../src/people/committers";

const USER_AGENT = "oss-knowledge-base/1.0 (+https://github.com/unknowntpo/oss-knowledge-base)";
const DEFAULT_CAPTURE = join(import.meta.dir, "../src/people/kafka-committers.capture.ts");

function option(name: string): string | undefined {
  const index = process.argv.indexOf(`--${name}`);
  return index === -1 ? undefined : process.argv[index + 1];
}

export function captureModule(capture: CommittersCaptureV1): string {
  return [
    "/**",
    " * Spec 019 amendment (7), owner resolution 3: the Kafka committers page's name ↔ GitHub-login",
    " * pairs, the precision check's truth set and `declared` link evidence. Generated by",
    " * `bun run refresh:committers`; review the printed diff in the PR instead of editing by hand.",
    " */",
    "import type { CommittersCaptureV1 } from \"./committers\";",
    "",
    `export const KAFKA_COMMITTERS_CAPTURE: CommittersCaptureV1 = ${JSON.stringify(capture, null, 2)};`,
    "",
  ].join("\n");
}

if (import.meta.main) {
  const reviewer = option("reviewer");
  if (reviewer === undefined || reviewer.trim() === "") {
    console.error("refresh:committers needs --reviewer <login> (who reviews the refresh PR)");
    process.exit(2);
  }
  const capturePath = option("capture") ?? DEFAULT_CAPTURE;
  const date = option("date") ?? new Date().toISOString().slice(0, 10);
  const htmlPath = option("html");
  const previous = (await import(capturePath)).KAFKA_COMMITTERS_CAPTURE as CommittersCaptureV1;
  let html: string;
  if (htmlPath !== undefined) html = await Bun.file(htmlPath).text();
  else {
    const response = await fetch(KAFKA_COMMITTERS_URL, { headers: { "User-Agent": USER_AGENT }, signal: AbortSignal.timeout(30_000) });
    if (!response.ok) {
      console.error(`${KAFKA_COMMITTERS_URL} answered HTTP ${response.status}`);
      process.exit(1);
    }
    html = await response.text();
  }
  const page = parseCommittersPage(html);
  if (page.length === 0) {
    console.error("The committers page has no committer card with a GitHub link; the capture is unchanged");
    process.exit(1);
  }
  const diff = refreshCommitters(previous, page, { date, reviewer: reviewer.trim(), source: KAFKA_COMMITTERS_URL });
  console.log(formatCommittersDiff(diff));
  if (!process.argv.includes("--check")) await Bun.write(capturePath, captureModule(diff.capture));
}
